// Writes src/components/icons.tsx from scripts/icon-map.json. Each export keeps
// the name call sites already use and renders a Hugeicons stroke-rounded icon.
// Run: node scripts/generate-icons.mjs
import { readFileSync, writeFileSync } from "node:fs";

const map = JSON.parse(
  readFileSync(new URL("./icon-map.json", import.meta.url), "utf8")
);
const sources = [...new Set(Object.values(map))].sort();
const exports = Object.entries(map)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(
    ([name, source]) =>
      `export const ${name} = icon(${source}Glyph, "${name}");`
  )
  .join("\n");

const file = `// Generated by scripts/generate-icons.mjs from scripts/icon-map.json. Edit the
// map, then run \`node scripts/generate-icons.mjs\`.
import { HugeiconsIcon, type IconSvgElement } from "@hugeicons/react";
import type { SVGProps } from "react";
import {
${sources.map((source) => `  ${source} as ${source}Glyph,`).join("\n")}
} from "@hugeicons/core-free-icons";

export type IconProps = Omit<SVGProps<SVGSVGElement>, "ref"> & {
  size?: number | string;
  strokeWidth?: number;
};

export type Icon = ((props: IconProps) => React.JSX.Element) & {
  displayName?: string;
};

/**
 * Wraps a Hugeicons glyph as a named icon component. Icons are decorative by
 * default (\`aria-hidden\`); pass an \`aria-label\` to expose one.
 */
function icon(glyph: IconSvgElement, name: string): Icon {
  const Component: Icon = ({ size = 24, strokeWidth = 1.75, ...props }) => (
    <HugeiconsIcon
      icon={glyph}
      size={size}
      strokeWidth={strokeWidth}
      aria-hidden={props["aria-label"] ? undefined : true}
      {...props}
    />
  );
  Component.displayName = name;
  return Component;
}

${exports}
`;

writeFileSync(new URL("../src/components/icons.tsx", import.meta.url), file);
console.log(`Wrote ${Object.keys(map).length} icons`);
